# Crear un array (lista) de frutas
frutas = ["manzana", "pera", "uva"]

# Acceder a un elemento por su índice (empieza en 0)
print(frutas[0])  # Resultado: manzana

# Modificar un elemento
frutas[1] = "naranja"

# Agregar un elemento al final
frutas.append("sandía")

# Conocer la cantidad de elementos
print(len(frutas))  # Resultado: 4
